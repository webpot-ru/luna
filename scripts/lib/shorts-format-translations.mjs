export function normalizeShortsLanguageCode(langCode) {
  const upper = String(langCode || "EN").trim().toUpperCase();
  if (upper === "NB") return "NB";
  if (shortsFormatTranslations[upper]) return upper;
  const base = upper.split("-")[0];
  return shortsFormatTranslations[base] ? base : "EN";
}

export function getShortsFormatTranslations(langCode) {
  const resolvedCode = normalizeShortsLanguageCode(langCode);
  const pack = shortsFormatTranslations[resolvedCode] || shortsFormatTranslations.EN;
  return {
    languageCode: resolvedCode,
    formats: pack.formats
  };
}

export function getShortsFormatTranslation(langCode, formatId = "word_quiz_3_2_1") {
  const resolvedFormatId = SHORTS_FORMAT_IDS.includes(formatId) ? formatId : "word_quiz_3_2_1";
  const pack = getShortsFormatTranslations(langCode);
  return {
    languageCode: pack.languageCode,
    formatId: resolvedFormatId,
    ...pack.formats[resolvedFormatId]
  };
}
