export const SHORTS_FORMAT_REQUIRED_FIELDS = [
  "hook",
  "answerLabel",
  "repeatPrompt",
  "commentPrompt",
  "profileCta"
];

function s({
  wordQuiz,
  audioFirst,
  sayBefore,
  sceneThree,
  chooseCorrect,
  speedReview,
  phraseLadder,
  visualObject,
  answerLabel,
  repeatPrompt,
  commentPrompt,
  profileCta
}) {
  const common = {
    answerLabel,
    repeatPrompt,
    commentPrompt,
    profileCta
  };
  return {
    formats: {
      word_quiz_3_2_1: { hook: wordQuiz, ...common },
      audio_first_quiz: { hook: audioFirst, ...common },
      say_it_before_me: { hook: sayBefore, ...common },
      three_words_one_scene: { hook: sceneThree, ...common },
      which_one_is_correct: { hook: chooseCorrect, ...common },
      speed_loop_5_words: { hook: speedReview, ...common },
      phrase_ladder: { hook: phraseLadder, ...common },
      visual_object_flash: { hook: visualObject, ...common }
    }
  };
}

