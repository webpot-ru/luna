export function getShortsOutroTranslation(supportLang) {
  const lang = String(supportLang || "").toUpperCase();
  const canonicalLang = shortsOutroAliases[lang] || lang;
  const baseLang = canonicalLang.split("-")[0];
  const translation =
    shortsOutroTranslations[canonicalLang] ||
    shortsOutroTranslations[baseLang] ||
    shortsOutroTranslations.EN;
  const override =
    shortsOutroCopyOverrides[lang] ||
    shortsOutroCopyOverrides[canonicalLang] ||
    shortsOutroCopyOverrides[baseLang] ||
    shortsOutroCopyOverrides.EN;

  return {
    ...translation,
    ...override
  };
}
