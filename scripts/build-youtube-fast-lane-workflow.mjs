#!/usr/bin/env node
import fs from "node:fs";
import { pathToFileURL } from "node:url";

// Keep the original controller intact. Regenerate this optional variant when it changes.
export function buildFastLaneWorkflow(source) {
  const replaceOnce = (from, to) => {
    if (source.split(from).length !== 2) throw new Error(`Controller anchor changed: ${from}`);
    source = source.replace(from, to);
  };
  replaceOnce("name: YouTube Publication Control", "# Generated by scripts/build-youtube-fast-lane-workflow.mjs; do not edit manually.\nname: YouTube Publication Fast Lane (experimental)");
  replaceOnce("permissions:\n  contents: read", [
    "      fast_apply:",
    '        description: "Explicitly approved single batch: fresh control, exact claim, then ONE standard parent dispatch. Default is preview only."',
    "        type: boolean", "        required: true", "        default: false",
    "      expected_assignment_count:",
    '        description: "Exact owner-approved total; a different result stops before claim."',
    "        type: string", "        required: true", '        default: "585"',
    "      fast_confirm_apply:", "        type: string", "        required: false", '        default: ""',
    '        description: "Apply only: APPLY_YOUTUBE_PUBLICATION_CAMPAIGN."',
    "      fast_confirm_metadata:", "        type: string", "        required: false", '        default: ""',
    '        description: "Apply only: USE_OPENAI_METADATA authorizes paid metadata for this batch."',
    "      recovery_source_campaign_id:", "        type: string", "        required: false", '        default: ""',
    '        description: "Optional terminal source campaign: recover source missing rows ONLY, without new videos."',
    "      recovery_source_manifest_hash:", "        type: string", "        required: false", '        default: ""',
    '        description: "Recovery only: exact immutable source hash."',
    "      recovery_assignment_keys:", "        type: string", "        required: false", '        default: ""',
    '        description: "Recovery only: approved JSON key array; empty selects ALL still-active source missing rows. Exact total remains mandatory."',
    "", "permissions:", "  contents: read",
    "", "concurrency:", "  group: youtube-publication-fast-lane-${{ github.ref_name }}", "  cancel-in-progress: false",
  ].join("\n"));
  replaceOnce("      - id: select\n", [
    "      - name: Validate explicit batch authorization", "        run: node scripts/youtube-fast-lane.mjs authorize", "      - id: select", "",
  ].join("\n"));
  replaceOnce("      - name: Claim the exact fresh no-spend plan\n", [
    "      - name: Check exact approved scope before any claim write", "        run: node scripts/youtube-fast-lane.mjs verify .claim-artifact",
    "      - name: Claim the exact fresh no-spend plan", "",
  ].join("\n"));
  // Preview also validates exact count and complete control, without writing claims.
  replaceOnce("          npm run plan:youtube-publication-campaign -- \"${ARGS[@]}\"", [
    "          if node scripts/youtube-fast-lane.mjs is-recovery; then",
    "            node scripts/youtube-fast-lane.mjs plan-recovery outputs .control-artifacts",
    "          else", '            npm run plan:youtube-publication-campaign -- "${ARGS[@]}"',
    "          fi", "          node scripts/youtube-fast-lane.mjs verify outputs",
  ].join("\n"));
  replaceOnce("            outputs/youtube-publication-campaign-plan.json", "            outputs/youtube-publication-campaign-plan.json\n            outputs/youtube-fast-lane-route-reports.json");
  replaceOnce("          node scripts/claim-youtube-publication-campaign.mjs --manifest=outputs/youtube-publication-campaign-plan.json --apply --confirm=CLAIM_YOUTUBE_PUBLICATION_CAMPAIGN --json", "          node scripts/youtube-fast-lane.mjs claim .claim-artifact");
  return source + [
    "", "  dispatch-approved-parent:", "    needs: [aggregate, claim-campaign]",
    "    if: ${{ needs.claim-campaign.result == 'success' && github.event.inputs.fast_apply == 'true' }}",
    "    runs-on: ubuntu-latest", "    permissions:", "      contents: read", "      actions: write",
    "    steps:", "      - uses: actions/checkout@v4", "        with:", "          ref: main", "          fetch-depth: 0",
    "      - uses: actions/setup-node@v4", "        with:", '          node-version: "20"',
    "      - uses: actions/download-artifact@v4", "        with:",
    "          name: youtube-publication-control-${{ github.event.inputs.set_id }}-all-routes-${{ github.run_id }}",
    "          path: .claim-artifact",
    "      - name: Verify claimed main and dispatch ONCE (no retries or watch)",
    "        env:", "          GH_TOKEN: ${{ github.token }}",
    "        run: node scripts/youtube-fast-lane.mjs dispatch .claim-artifact",
    "      - uses: actions/upload-artifact@v4", "        if: always()", "        with:",
    "          name: youtube-fast-lane-dispatch-${{ github.run_id }}", "          if-no-files-found: ignore",
    "          path: |", "            outputs/youtube-fast-lane-dispatch.json", "            outputs/youtube-fast-lane-preflight.json", "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = ".github/workflows/youtube-publication-fast-lane.yml";
  const generated = buildFastLaneWorkflow(fs.readFileSync(".github/workflows/youtube-publication-control.yml", "utf8"));
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== generated) throw new Error("Fast lane must be regenerated from the current controller");
  } else fs.writeFileSync(target, generated);
}
